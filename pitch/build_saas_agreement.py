def _rtl_para(p):
    pPr = p._p.get_or_add_pPr()
    pPr.append(OxmlElement("w:bidi"))
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT


def _cs(run):
    """Mark run text as complex-script so Hebrew uses the cs font/size."""
    rPr = run._element.get_or_add_rPr()
    rfonts = rPr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rPr.append(rfonts)
    rfonts.set(qn("w:cs"), FONT)
    rfonts.set(qn("w:ascii"), FONT)
    rfonts.set(qn("w:hAnsi"), FONT)


# pPr child order per OOXML schema — used to insert pBdr/shd in the right slot.
_PPR_AFTER_PBDR = (
    "w:shd", "w:tabs", "w:suppressAutoHyphens", "w:kinsoku", "w:wordWrap",
    "w:overflowPunct", "w:topLinePunct", "w:autoSpaceDE", "w:autoSpaceDN",
    "w:bidi", "w:adjustRightInd", "w:snapToGrid", "w:spacing", "w:ind",
    "w:contextualSpacing", "w:mirrorIndents", "w:suppressOverlap", "w:jc",
    "w:textDirection", "w:textAlignment", "w:textboxTightWrap", "w:outlineLvl",
    "w:divId", "w:cnfStyle", "w:rPr", "w:sectPr", "w:pPrChange",
)
_TBLPR_AFTER_BIDIVISUAL = (
    "w:tblStyleRowBandSize", "w:tblStyleColBandSize", "w:tblW", "w:jc",
    "w:tblCellSpacing", "w:tblInd", "w:tblBorders", "w:shd", "w:tblLayout",
    "w:tblCellMar", "w:tblLook", "w:tblCaption", "w:tblDescription",
    "w:tblPrChange",
)


def _add_pbdr(pPr, pbdr):
    pPr.insert_element_before(pbdr, *_PPR_AFTER_PBDR)


def _add_shd(pPr, shd):
    pPr.insert_element_before(shd, *_PPR_AFTER_PBDR[1:])


def heading(doc, text, size=15, color=BOLT, rule=True, before=10, after=5):
    p = doc.add_paragraph()
    _rtl_para(p)
    r = p.add_run(text)
    r.bold = True
    r.font.name = FONT
    r.font.color.rgb = color
    r.font.size = Pt(size)
    _cs(r)
    if rule:
        pPr = p._p.get_or_add_pPr()
        pbdr = OxmlElement("w:pBdr")
        bottom = OxmlElement("w:bottom")
        bottom.set(qn("w:val"), "single")
        bottom.set(qn("w:sz"), "6")
        bottom.set(qn("w:space"), "4")
        bottom.set(qn("w:color"), "C9622F")
        pbdr.append(bottom)
        _add_pbdr(pPr, pbdr)
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.space_after = Pt(after)
    return p


def body(doc, text, bold=False, color=None, size=10.5, italic=False, space=5,
         indent=0, align=None):
    p = doc.add_paragraph()
    _rtl_para(p)
    if indent:
        p.paragraph_format.right_indent = Pt(indent)
    if align is not None:
        p.alignment = align
    r = p.add_run(text)
    r.bold = bold
    r.italic = italic
    r.font.name = FONT
    r.font.size = Pt(size)
    if color:
        r.font.color.rgb = color
    _cs(r)
    p.paragraph_format.space_after = Pt(space)
    return p


def runs_para(doc, parts, size=10.5, space=5, indent=0):
    """parts = list of (text, bold) tuples in one paragraph."""
    p = doc.add_paragraph()
    _rtl_para(p)
    if indent:
        p.paragraph_format.right_indent = Pt(indent)
    for text, bold in parts:
        r = p.add_run(text)
        r.bold = bold
        r.font.name = FONT
        r.font.size = Pt(size)
        _cs(r)
    p.paragraph_format.space_after = Pt(space)
    return p


def callout(doc, text, color=UP, fill="FBEAE5"):
    p = doc.add_paragraph()
    _rtl_para(p)
    pPr = p._p.get_or_add_pPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:fill"), fill)
    pbdr = OxmlElement("w:pBdr")
    for edge in ("top", "left", "bottom", "right"):
        e = OxmlElement(f"w:{edge}")
        e.set(qn("w:val"), "single")
        e.set(qn("w:sz"), "6")
        e.set(qn("w:space"), "6")
        e.set(qn("w:color"), "B4472D")
        pbdr.append(e)
    _add_pbdr(pPr, pbdr)
    _add_shd(pPr, shd)
    p.paragraph_format.space_before = Pt(4)
    p.paragraph_format.space_after = Pt(8)
    r = p.add_run(text)
    r.bold = True
    r.font.name = FONT
    r.font.size = Pt(10)
    r.font.color.rgb = color
    _cs(r)
    return p


def make_table(doc, rows, header=True, widths=None):
    t = doc.add_table(rows=0, cols=len(rows[0]))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.RIGHT
    tblPr = t._tbl.tblPr
    tblPr.insert_element_before(OxmlElement("w:bidiVisual"),
                                *_TBLPR_AFTER_BIDIVISUAL)
    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        for ci, val in enumerate(row):
            cell = cells[ci]
            cell.text = ""
            p = cell.paragraphs[0]
            _rtl_para(p)
            r = p.add_run(val)
            r.font.name = FONT
            r.font.size = Pt(9.5)
            _cs(r)
            if ri == 0 and header:
                r.bold = True
                r.font.color.rgb = RGBColor(0xff, 0xff, 0xff)
                shd = OxmlElement("w:shd")
                shd.set(qn("w:val"), "clear")
                shd.set(qn("w:fill"), "5C3317")
                cell._tc.get_or_add_tcPr().append(shd)
    return t


def spacer(doc, size=4):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(size)


def add_page_number_footer(section):
    footer = section.footer
    p = footer.paragraphs[0]
    _rtl_para(p)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run("טיוטה לדיון — אינה ייעוץ משפטי  |  עמוד ")
    r.font.name = FONT
    r.font.size = Pt(8)
    r.font.color.rgb = SUB
    _cs(r)
    # PAGE field
    fld = OxmlElement("w:fldSimple")
    fld.set(qn("w:instr"), "PAGE")
    run_el = OxmlElement("w:r")
    rpr = OxmlElement("w:rPr")
    sz = OxmlElement("w:sz"); sz.set(qn("w:val"), "16")
    rpr.append(sz)
    run_el.append(rpr)
    t = OxmlElement("w:t"); t.text = "1"
    run_el.append(t)
    fld.append(run_el)
    p._p.append(fld)


