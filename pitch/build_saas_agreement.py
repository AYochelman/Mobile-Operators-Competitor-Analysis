def emit_section(doc, num, title, items):
    heading(doc, f"{num}. {title}")
    sub = 0
    for item in items:
        if isinstance(item, tuple):
            kind, text = item
            if kind == "i":          # indented sub-sub-clause, e.g. (א)
                body(doc, text, indent=30, space=3, size=10)
            elif kind == "p":        # plain indented note under a sub-clause
                body(doc, text, indent=18, space=3, size=10, color=SUB)
        else:
            sub += 1
            runs_para(doc, [(f"{num}.{sub}.  ", True), (item, False)], space=4)


